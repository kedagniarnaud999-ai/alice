/**
 * Conteneur des chances reliées à un métier : où se former, quelle formation
 * courte, comment financer. Un nom d'école ou de bourse inventé enverrait un
 * candidat vers un établissement qui n'existe pas, ce qui est pire qu'une case
 * vide : une ligne ne vaut que par le lien qui l'a fait exister.
 *
 * Comment remplir ce catalogue (dans l'ordre de fiabilité) :
 *  1. une liste fournie par l'équipe (partenaires, annuaire déjà contrôlé) :
 *     `source: 'fourni'`, une `url` réelle et `verifiedAt` à la date de contrôle ;
 *  2. une table backend exposée par l'API (Lot 2) : le même format JSON, et ce
 *     fichier ne devient que le repli hors ligne ;
 *  3. le jeu de démonstration ci-dessous, qui n'a d'autre rôle que de prouver
 *     l'appariement et l'affichage. `source: 'demo'` interdit l'`url` : l'UI
 *     affiche un badge « Démo » tant qu'une chance n'est pas passée en 'fourni'
 *     ou 'verifie'.
 *
 * Les lignes 'fourni' viennent de l'export d'annuaire remis par l'équipe (Bénin,
 * septembre 2026). Nom et lien y sont repris tels que reçus, `verifiedAt` porte la
 * date où le lien a effectivement répondu. Quand le site officiel d'une école ne
 * répond pas, ne l'identifie pas ou détourne vers un autre domaine, l'`url` pointe
 * sur la fiche d'annuaire fournie pour cette même école — jamais sur une adresse
 * devinée. Les `domainIds` ne disent que ce que la liste atteste : les diplômes
 * qui rattachent à l'école, complétés par son intitulé officiel quand aucun
 * diplôme n'y est rattaché.
 */
export type OpportunityKind = 'etablissement' | 'formation' | 'bourse';

export type OpportunitySource = 'demo' | 'fourni' | 'verifie';

