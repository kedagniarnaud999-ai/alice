/**
 * Le référentiel de métiers reçu du fondateur, recopié tel quel : 14 domaines, 11 fonctions,
 * 84 métiers génériques, 113 spécialisations. Source : Classification_Metiers_Benin_FINAL.xlsx,
 * classification_metiers_benin_final.json et Fiches_Metiers_113_AliTche.docx — la base corrigée du
 * 3 octobre 2026, qui remplace la V3 du même jour (63 métiers génériques, dont plusieurs tiroirs
 * partagés entre tous les domaines : le même « Technicien de production » ouvrait l'infirmier comme
 * l'hydrologue).
 *
 * Ce fichier ne remplace rien du moteur de score. Il ajoute trois choses que le catalogue n'avait pas :
 * une nomenclature validée à deux, un métier générique au-dessus du métier nommé, et le contenu rédactionnel
 * de chaque spécialisation (définition, compétences, formation et accès, débouchés).
 *
 * Ce qui est à nous, et donc à défendre seuls :
 * - 'domaine hôte' : ses 14 domaines se logent dans nos 11 domaines de carrière,
 *   notre catalogue de score restant le seul que le questionnaire sait mesurer ;
 * - 'axes' : ses 11 fonctions se répartissent sur nos six axes scorés, en poids qui sommant 1 ;
 * - le rang de nos 45 fiches sous ses métiers génériques.
 *
 * 'qualifieParDomaine' vient de sa colonne « Portée » : 38 de ses 84 métiers ne servent qu'un domaine,
 * les 46 autres restent transversaux. Elle se lit une fois sur le métier, plus une fois par ligne : sa base
 * corrigée nomme elle-même le parent de chaque spécialisation, donc aucun lien d'ici n'est une supposition.
 * L'à-peu-près qui reste dans ce fichier est le rang de nos fiches, et lui seul. Aucune de ses lignes ne
 * contredit la fonction de son parent — les deux exceptions de la V3 (SP084 et SP085) sont reclassées avec lui.
 */

export interface ReferentielDomaine {
  code: string;
  libelle: string;
  description: string;
  /** Le domaine de carrière du moteur qui l'héberge. Plusieurs de ses domaines peuvent en loger un seul. */
  hote: FunctionalDomainId;
  /** Vrai quand l'hébergement est un arrangement, pas un équivalent. */
  hebergementApproximatif: boolean;
}

export interface ReferentielFonction {
  code: string;
  libelle: string;
  description: string;
  /** Répartition sur les six axes scorés. Les poids somment 1. */
  axes: { axe: FunctionRoleId; poids: number }[];
}

export interface ReferentielMetier {
  code: string;
  libelle: string;
  fonction: string;
  /** Vrai quand sa « Portée » le limite à un domaine : il n'est pas partagé entre tous. */
  qualifieParDomaine: boolean;
}

export interface ReferentielSpecialisation {
  code: string;
  libelle: string;
  domaine: string;
  fonction: string;
  /** Le métier générique dont cette spécialisation est la déclinaison dans ce domaine. */
  parent: string;
  definition: string;
  competences: string[];
  formation: string;
  debouches: string;
}

